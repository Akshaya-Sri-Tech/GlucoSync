
CREATE TABLE IF NOT EXISTS patients (
    patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    age INT CHECK (age > 0),
    diabetes_type VARCHAR(50),
    min_glucose NUMERIC(6,2),
    max_glucose NUMERIC(6,2),
    CHECK (
        min_glucose IS NULL
        OR max_glucose IS NULL
        OR min_glucose < max_glucose
    )
);

CREATE TABLE IF NOT EXISTS doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS glucose_readings (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    glucose_value NUMERIC(6,2) NOT NULL CHECK (glucose_value > 0),
    reading_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(10) NOT NULL
        CHECK (status IN ('Normal', 'High', 'Low')),
    meal_context VARCHAR(10) NOT NULL
        CHECK (meal_context IN ('Pre-meal', 'Post-meal'))
);

CREATE TABLE IF NOT EXISTS doctor_slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id),
    slot_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (end_time > start_time),
    UNIQUE (doctor_id, slot_date, start_time)
);

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id),
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id),
    slot_id BIGINT NOT NULL UNIQUE REFERENCES doctor_slots(slot_id),
    status VARCHAR(15) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Booked', 'Cancelled', 'Completed'))
);
